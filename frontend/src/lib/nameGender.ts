/**
 * Infer sexo (M/F) from common Spanish/Latino given names.
 * First token of "nombres" is used. User can always override in the UI.
 */

export type InferredSexo = "M" | "F";

function stripDiacritics(s: string): string {
  return s.normalize("NFD").replace(/\p{M}/gu, "");
}

function firstGivenName(nombres: string): string {
  const raw = (nombres || "").trim().split(/\s+/)[0] || "";
  return stripDiacritics(raw).toLowerCase().replace(/[^a-zñ]/g, "");
}

