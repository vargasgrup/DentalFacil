/** Male names that end with "a" (heuristic exceptions). */
const MALE_ENDING_A = new Set(
  ["joshua", "judas", "luca", "elisha", "jonah", "noah", "asia"].map((n) =>
    stripDiacritics(n)
  )
);

/** Female names that end with "o" / consonant (heuristic exceptions). */
const FEMALE_ENDING_O = new Set(
  ["consuelo", "amparo", "socorro", "pilar", "carmen", "ines", "beatriz", "luz", "cruz"].map(
    (n) => stripDiacritics(n)
  )
);

/**
 * Guess M/F from given names, or null if uncertain.
 * Uses: dictionary first, then simple Spanish ending heuristics.
 */
export function inferSexoFromNombres(nombres: string): InferredSexo | null {
  const name = firstGivenName(nombres);
  if (!name || name.length < 2) return null;

  if (FEMALE_NAMES.has(name)) return "F";
  if (MALE_NAMES.has(name)) return "M";

  // Compound first parts already covered by first token (María …, Juan …).
  if (MALE_ENDING_A.has(name)) return "M";
  if (FEMALE_ENDING_O.has(name)) return "F";

  if (name.endsWith("a") && !MALE_ENDING_A.has(name)) return "F";
  if (name.endsWith("o") && !FEMALE_ENDING_O.has(name)) return "M";

  // Diminutives: -ita / -ina often female; -ito often male.
  if (name.endsWith("ita") || name.endsWith("ina") || name.endsWith("ela")) return "F";
  if (name.endsWith("ito") || name.endsWith("ico")) return "M";

  return null;
}
